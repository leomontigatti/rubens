import { betterAuth } from "better-auth";
import { getMigrations } from "better-auth/db/migration";
import { organization } from "better-auth/plugins/organization";
import { tanstackStartCookies } from "better-auth/tanstack-start";
import { env as workerEnv } from "cloudflare:workers";

import { ac, roles } from "./access";
import type { Env } from "./env";
import { countingD1 } from "./request-stats";

const env = workerEnv as unknown as Env;

// Outside production a missing secret falls back to a fixed dev value, so a fresh
// clone runs with no .env. A production build refuses to start without one.
const devSecret = "rubens-prototype-dev-secret-not-for-production-0123456789";

function secret(): string {
  if (env.BETTER_AUTH_SECRET) return env.BETTER_AUTH_SECRET;
  if (import.meta.env.DEV) return devSecret;
  throw new Error(
    "BETTER_AUTH_SECRET is required in production (wrangler secret put BETTER_AUTH_SECRET)",
  );
}

function createAuth() {
  return betterAuth({
    // Better Auth detects a D1 binding and uses its own Kysely D1 dialect.
    database: countingD1(env.DB),
    secret: secret(),
    baseURL: env.BETTER_AUTH_URL,
    emailAndPassword: { enabled: true, disableSignUp: true },
    databaseHooks: {
      session: {
        create: {
          // As in rubens: a member belongs to one organization, so every session starts in it.
          before: async (session) => {
            const row = await countingD1(env.DB)
              .prepare('select "organizationId" from member where "userId" = ? limit 1')
              .bind(session.userId)
              .first<{ organizationId: string }>();
            return { data: { ...session, activeOrganizationId: row?.organizationId ?? null } };
          },
        },
      },
    },
    plugins: [organization({ ac, roles, creatorRole: "admin" }), tanstackStartCookies()],
  });
}

export type Auth = ReturnType<typeof createAuth>;

let auth: Auth | undefined;
let migrated: Promise<void> | undefined;

/**
 * The isolate's Better Auth. Its D1 tables are created on first use, in dev and in
 * production alike (Better Auth's own migrator, which diffs the live schema); a real
 * port would ship `wrangler d1 migrations` generated by `@better-auth/cli generate`.
 */
export async function getAuth(): Promise<Auth> {
  auth ??= createAuth();
  migrated ??= getMigrations(auth.options).then(
    async ({ runMigrations, toBeCreated, toBeAdded }) => {
      if (toBeCreated.length || toBeAdded.length) await runMigrations();
    },
  );
  try {
    await migrated;
  } catch (error) {
    migrated = undefined;
    throw error;
  }
  return auth;
}

/** As rubens: the organization plugin's HTTP endpoints are refused; the app calls it through auth.api. */
export async function handleAuthRequest(request: Request): Promise<Response> {
  if (new URL(request.url).pathname.startsWith("/api/auth/organization/")) {
    return new Response(null, { status: 404 });
  }
  return (await getAuth()).handler(request);
}

export { env };
